// easy-edits style <list | validate <pack> | skill <pack>>: work with style packs (engine/style-pack.mjs).
//   list                         every pack found (built-in + ~/.easy-edits/styles), valid or not
//   validate <pack>              check a pack against the schema and the extra rules; exit 1 when it is invalid
//   skill <pack> [-o DIR] [--project] [--print]
//                                write a Claude Code skill that edits in that style: DIR/easy-edits-style-<id>/SKILL.md
//                                (default DIR ~/.claude/skills, the personal skills every project sees; --project:
//                                ./.claude/skills; --print: to stdout)
// <pack> is a built-in id (punch, broadsheet, terminal), an id in ~/.easy-edits/styles, or a path to a pack .json.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { loadPack, listPacks, resolvePack, missingFonts, StyleError, PACK_DIR, userDir } from '../engine/style-pack.mjs';

export const STYLE_HELP = `usage: easy-edits style list
       easy-edits style validate <pack>
       easy-edits style skill <pack> [-o DIR | --project | --print]

  <pack>   a built-in style id, an id in ~/.easy-edits/styles (EASY_EDITS_STYLES), or a path to a pack .json
  list     every pack found, with its status
  validate check the pack against easy-edits/styles/pack.schema.json and the extra rules (exit 1 when invalid)
  skill    write a Claude Code skill that edits in that style, to DIR/easy-edits-style-<id>/SKILL.md
           (default DIR ~/.claude/skills; --project: ./.claude/skills; --print: stdout only)

Render with a style: easy-edits <captions|talking-head|explainer|shorts> VIDEO -o OUT --style <pack>
`;

const SCENE_TEXT = {
  punch: 'punch-ins (zoom on the speaker)', icon: 'icon pops', stat: 'stat pops (numbers)', quote: 'quote boxes', list: 'list boxes',
  compare: 'compare boxes (X vs Y)', card: 'card boxes', 'lower-third': 'lower third (name / role)', hook: 'hook card (shorts --hook)',
  progress: 'progress bar', intro: 'intro title card', outro: 'end card',
};
const TRANSITION_TEXT = { cut: 'hard cuts', whip: 'a whip-pan smear in the accent colour, with motion blur', dip: 'a soft dip through the background colour', glitch: 'an RGB-split glitch with a jitter' };
const NUMBERS_TEXT = { slam: 'the value slams in from 3x and the pop shakes', 'count-up': 'the value counts up from zero like a ticker', scramble: 'the digits decode through random numbers' };
const SIGNATURE_TEXT = { 'punch-shake': 'a zoom hit with a short camera shake and an accent frame flash', letterbox: 'cinematic letterbox bars with an accent rule slide in', hud: 'HUD corner brackets lock onto the face over faint scanlines' };
const HL_TEXT = { none: 'no highlight', keywords: 'numbers and the plan\'s key words light up when spoken', 'active-word': 'the word being spoken lights up' };

/** the shell argument for --style: the id when the id resolves to this same file, else the absolute path. */
export function styleRef(pack) {
  try { if (resolvePack(pack.id).file === pack.file) return pack.id; } catch { /* not findable by id */ }
  return pack.file;
}

/** SKILL.md text for a validated pack. */
export function skillMarkdown(pack, { ref = styleRef(pack) } = {}) {
  const P = pack.palette, C = pack.captions, M = pack.motion, Pa = pack.pacing, allow = new Set(pack.scenes);
  const q = /\s/.test(ref) ? `"${ref}"` : ref;
  const not = Object.keys(SCENE_TEXT).filter((k) => !allow.has(k));
  const beats = ['punch', 'icon', 'stat', 'quote', 'list', 'compare', 'card'];
  const desc = `Use when the user wants a video edited in the "${pack.name}" style (Easy Edits style pack "${pack.id}")${pack.useFor ? `, or asks for an edit suited to it: ${pack.useFor.replace(/\.$/, '')}` : ''}. ${pack.description} Renders with easy-edits --style ${ref}.`;
  const cmds = {
    captions: `easy-edits captions VIDEO.mp4 -o OUT --style ${q}`,
    'talking-head': `easy-edits talking-head VIDEO.mp4 -o OUT --style ${q}`,
    explainer: `easy-edits explainer VIDEO.mp4 -o OUT --style ${q} --script script.md`,
    shorts: `easy-edits shorts VIDEO.mp4 -o OUT --propose            # then, with the user's picks:\neasy-edits shorts VIDEO.mp4 -o OUT --pick 1,3 --style ${q}${allow.has('hook') ? ' --hook' : ''}${beats.some((b) => allow.has(b)) ? ' --graphics' : ''}`,
  };
  return `---
name: easy-edits-style-${pack.id}
description: ${JSON.stringify(desc)}
---

# ${pack.name} style (Easy Edits)

Generated by \`easy-edits style skill\` from the style pack \`${path.basename(pack.file)}\` (id \`${pack.id}\`, schema v${pack.schemaVersion}).
If the pack changes, generate this skill again; the pack, not this file, is what the renderer reads.

${pack.description}${pack.useFor ? `\n\nGood for: ${pack.useFor}` : ''}

## Edit in this style

Easy Edits must be installed (\`./install.sh\`, then \`./install.sh --doctor\` ends with "doctor: all PASS"; the
\`easy-edits\` skill covers setup). In every new shell run \`. ~/.easy-edits/env.sh\` first.

While this style is in use, add \`--style ${q}\` to EVERY Easy Edits render. It works with these modes:

\`\`\`sh
${pack.modes.map((m) => cmds[m]).join('\n')}
\`\`\`

- Formats: \`--format ${pack.formats.join('|')}\`${pack.formats.length > 1 ? ' (or several, comma separated)' : ''}${pack.formats.length === 3 ? ' or `all`' : ''}.
- \`clean-cut\` does not take a style (it keeps the approved caption look). \`talking-head\` makes the same clean
  cut${pack.modes.includes('talking-head') ? ' and renders it in this style' : ''}; \`captions\` captions a video in this style without cutting it.
- The renderer refuses what the style doesn't support (a mode or format it doesn't list, a --plan beat it doesn't
  allow${allow.has('hook') ? '' : ', --hook'}${allow.has('lower-third') ? '' : ', --speaker / --people'}) and prints why: fix the command, don't work around it.
- Music: ${pack.sound.music ? `"${pack.sound.music}" from Openverse (CC0 / CC BY) for talking-head and explainer; \`--music "query"\` or \`--no-music\` override it` : 'none by default; `--music "query"` adds one'}. Keep the \`CREDITS.txt\` with the video.
- Sound effects: ${pack.sound.sfx === 'full' ? 'all of them' : pack.sound.sfx === 'soft' ? 'whooshes only (no clicks or taps)' : 'none'}.

## The look

| part | ${pack.name} |
|------|------|
| palette | background ${P.background}, panels ${P.surface}, text ${P.text}, accent ${P.accent}, second ${P.accent2}, on accent ${P.onAccent} |
| fonts | titles ${pack.fonts.display.family} ${pack.fonts.display.weight}, body ${pack.fonts.body.family} ${pack.fonts.body.weight}, numbers ${pack.fonts.numbers.family} ${pack.fonts.numbers.weight} |
| captions | ${pack.fonts[C.font].family} ${C.weight}, ${C.size} px on 9:16, ${C.case === 'as-spoken' ? 'case as spoken' : `${C.case}case`}, up to ${C.maxWords} word(s) / ${C.maxChars} characters, ${C.animation === 'type' ? 'typed on word by word' : C.animation === 'fade-up' ? 'rising in' : C.animation === 'pop' ? 'popping in' : 'no animation'}; ${HL_TEXT[C.highlight]}${C.highlight === 'none' ? '' : ` (${C.highlightStyle})`} |
| caption colour | ${C.color === 'auto' ? 'auto contrast: white text with a dark edge, or near-black text with a light edge where the footage behind is bright' : C.color} |
| transitions | ${TRANSITION_TEXT[M.transition]}${M.transition === 'cut' ? '' : ` (${M.transitionDuration} s)`} at every layout change |
| numbers | ${NUMBERS_TEXT[M.numbers]} |
| signature move | ${SIGNATURE_TEXT[M.signature]}, on every punch-in |
| pacing | at least ${Pa.minBeatGap} s between pops / punch-ins, at most ${Pa.maxBeatsPerMinute} beats a minute, punch-ins ${Pa.punchZoom[0]}-${Pa.punchZoom[1]}x |

Scenes this style uses: ${pack.scenes.map((s) => SCENE_TEXT[s]).join(', ')}.${not.length ? `\nNot in this style: ${not.map((s) => SCENE_TEXT[s]).join(', ')}.` : ''}

## Planning in this style

To steer the graphics, run with \`--plan-only\`, edit the plan JSON it prints (schema at the top of
\`easy-edits/engine/plan.mjs\`; anchors are exact transcript phrases), then re-run with \`--plan FILE --style ${q}\`.

- Use only these beat types: ${beats.filter((b) => allow.has(b)).map((b) => `\`${b}\``).join(', ') || 'none'}. A plan file with any other type is refused.${beats.filter((b) => !allow.has(b)).length ? `\n- Never write ${beats.filter((b) => !allow.has(b)).map((b) => `\`${b}\``).join(', ')} beats for this style.` : ''}
- Keep ${Pa.minBeatGap} s or more between pops and punch-ins and no more than ${Pa.maxBeatsPerMinute} beats in any minute; the
  renderer leaves out the extras (report.json \`styleDropped\` lists them).
- Punch-in \`zoom\` between ${Pa.punchZoom[0]} and ${Pa.punchZoom[1]}.${allow.has('stat') ? '\n- Put the number exactly as spoken in a `stat` beat\'s `value` (it gets the style\'s number treatment).' : ''}
- Never guess a person's name: \`--speaker\` / \`--role\` only with names the user gave you.

## Review

1. Open every \`*_sheet.png\` contact sheet: faces in frame, captions readable (dark text on bright footage is
   expected: that is auto contrast), the style's colours and fonts on the cards.
2. Read the \`*.report.json\`: per export \`style\` (should be \`${pack.id}\`), \`transitions\`, \`signatures\`,
   \`styleDropped\` (beats left out for this style), \`contrast\` (how many captions went light / dark), \`overlaps\`
   and the delivery \`check\`.
3. The CLI exits 1 when an export has a delivery FAIL even though the mp4 was written. Tell the user every FAIL
   with its text; look it up in \`KNOWN_ISSUES.txt\` in the Easy Edits checkout; never hide one or call the run done.
4. If the face framing is wrong (a poster, a second person, a dark shot), re-run with \`--face top|center|bottom\`
   or \`--face X,Y\` (fractions of the frame, e.g. \`--face 0.3,0.4\`).

## Rules

- Only edit videos the user owns or has the rights to edit.
- Never upload, post or publish anything, and never send the user's media to an online service, unless the user
  explicitly asks.
- Keep the user's videos and renders outside the Easy Edits checkout.
`;
}

const out = (s) => process.stdout.write(s), err = (s) => process.stderr.write(s);

export function styleMain(argv) {
  const [cmd, ...rest] = argv;
  if (!cmd || cmd === '-h' || cmd === '--help') { out(STYLE_HELP); return cmd ? 0 : 2; }
  const flags = new Set(rest.filter((a) => a.startsWith('-')));
  const oi = rest.findIndex((a) => a === '-o' || a === '--out');
  const pos = rest.filter((a, i) => !a.startsWith('-') && (oi < 0 || i !== oi + 1));
  try {
    if (cmd === 'list') {
      const packs = listPacks();
      out(`style packs (built-in: ${PACK_DIR}; yours: ${userDir()})\n`);
      for (const p of packs) {
        out(`\n  ${p.id.padEnd(12)} ${p.name}${p.builtin ? '' : '  (yours)'}${p.ok ? '' : `  INVALID (${p.errors.length} problem${p.errors.length > 1 ? 's' : ''}; easy-edits style validate ${p.file})`}\n`);
        if (p.description) out(`               ${p.description.replace(/(.{1,96})(\s+|$)/g, '$1\n               ').trimEnd()}\n`);
      }
      out(`\nRender with one: easy-edits <captions|talking-head|explainer|shorts> VIDEO -o OUT --style <id>\n`);
      return 0;
    }
    if (cmd === 'validate') {
      if (pos.length !== 1) { err('usage: easy-edits style validate <pack>\n'); return 2; }
      let pack;
      try { pack = loadPack(pos[0]); } catch (e) {
        if (e instanceof StyleError && e.errors.length) { err(`INVALID ${e.message}\n`); return 1; }
        throw e;
      }
      out(`OK ${pack.id} (${pack.file}): "${pack.name}"\n  modes ${pack.modes.join(', ')}; formats ${pack.formats.join(', ')}\n  scenes ${pack.scenes.join(', ')}\n  motion: ${pack.motion.transition} transitions, ${pack.motion.numbers} numbers, ${pack.motion.signature} signature; captions ${pack.captions.color === 'auto' ? 'auto contrast' : pack.captions.color}\n`);
      const miss = missingFonts(pack);
      if (miss.length) out(`  WARN font(s) not installed: ${miss.join(', ')}; renders with this pack are refused until you run ./install.sh\n`);
      return 0;
    }
    if (cmd === 'skill') {
      if (pos.length !== 1) { err('usage: easy-edits style skill <pack> [-o DIR | --project | --print]\n'); return 2; }
      let pack;
      try { pack = loadPack(pos[0]); } catch (e) {
        if (e instanceof StyleError && e.errors.length) { err(`no skill written: ${e.message}\n`); return 1; }
        throw e;
      }
      const md = skillMarkdown(pack);
      if (flags.has('--print')) { out(md); return 0; }
      if (oi >= 0 && !rest[oi + 1]) { err('-o needs a directory\n'); return 2; }
      const dir = oi >= 0 ? path.resolve(rest[oi + 1]) : flags.has('--project') ? path.resolve('.claude/skills') : path.join(process.env.HOME || os.homedir(), '.claude', 'skills');
      const file = path.join(dir, `easy-edits-style-${pack.id}`, 'SKILL.md');
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, md);
      out(`${file}\n`);
      err(`skill easy-edits-style-${pack.id} written; Claude Code picks it up in new sessions (it adds --style ${styleRef(pack)} to every render)\n`);
      return 0;
    }
    err(`unknown style command "${cmd}"\n${STYLE_HELP}`);
    return 2;
  } catch (e) {
    if (e instanceof StyleError) { err(`easy-edits: ${e.message}\n`); return 2; }
    throw e;
  }
}
