#!/usr/bin/env node
// Presenter short, standalone runner (wired into `ai-video-editor new presenter` at merge).
//   node ai-video-editor/presenter/run.mjs --script script.txt -o out/ [options]
// Exit: 0 rendered (or plan written), 1 an export failed a delivery check, 2 refused / bad request.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { planPresenter, planText, renderPresenter, planHash, PresenterError } from './pipeline.mjs';
import { PendingAssetsError, pendingMessage, EXIT_PENDING } from '../new/hostflow.mjs';

export const PRESENTER_HELP = `ai-video-editor presenter: a 9:16 15-90 s short read by a synthetic presenter, captioned from the script.

usage: node ai-video-editor/presenter/run.mjs (--script FILE | --text "...") -o OUT [options]

  --script FILE           the script (.txt / .md); or --text "..."
  -o, --out DIR           output directory (required)
  --length S              target length, 15-90 s (the script must fit it)
  --likeness fictional    (default) a fictional host: generated by the image backend, or --host-image FILE with
                          --host-license "who made it + the licence"
  --likeness self         your own face and/or voice; needs --consent consent.json (ai-video-editor consent create ...)
  --use face|voice|both   with --likeness self: what to synthesise (default both; voice uses tts voiceClone)
  --subject NAME          with --likeness self: the name on the consent record (checked)
  --host-prompt "..."     prompt for a generated fictional host
  --voice V               stock voice name for the tts backend
  --backend NAME          generation backend for every kind (none | mock | ...; AI_VIDEO_EDITOR_BACKEND overrides).
  --image-backend / --tts-backend / --avatar-backend NAME   one kind only. avatar "none" = a local still of the
                          host with subtle motion (no lip-sync)
  --no-disclosure         leave out the on-screen "AI-generated presenter" label (report.json still says synthetic)
  --disclosure-text "..." label text
  --plan-only             write plan.json + PLAN.txt and stop
  --approve FILE          render this approved plan.json (needed when a network backend would receive anything)
  --offline               refuse any network backend
  -h, --help
`;

const VALUE = new Set(['-o', '--out', '--script', '--text', '--length', '--likeness', '--use', '--consent', '--subject', '--host-image', '--host-license', '--host-prompt', '--voice', '--backend', '--image-backend', '--tts-backend', '--avatar-backend', '--disclosure-text', '--approve', '--name']);

export function parsePresenterArgs(argv) {
  const o = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const key = a.replace(/^-+/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());
    if (a === '-h' || a === '--help') o.help = true;
    else if (VALUE.has(a)) { if (i + 1 >= argv.length) throw new PresenterError(`${a} needs a value`); o[key] = argv[++i]; }
    else if (a === '--no-disclosure') o.disclosure = false;
    else if (['--plan-only', '--offline'].includes(a)) o[key] = true;
    else throw new PresenterError(`unknown option ${a}`);
  }
  if (o.o) o.out = o.o;
  return o;
}

export async function presenterMain(argv, { log = (m) => process.stderr.write(`ai-video-editor: ${m}\n`) } = {}) {
  let o;
  try { o = parsePresenterArgs(argv); } catch (e) { log(e.message); return 2; }
  if (o.help) { process.stdout.write(PRESENTER_HELP); return 0; }
  if (!o.out) { log('-o <out-dir> is required'); process.stdout.write(PRESENTER_HELP); return 2; }
  const out = path.resolve(o.out);
  try {
    const plan = planPresenter({ ...o, script: o.script && path.resolve(o.script), consent: o.consent && path.resolve(o.consent), hostImage: o.hostImage && path.resolve(o.hostImage) });
    fs.mkdirSync(out, { recursive: true });
    const planFile = path.join(out, `ai-video-editor_presenter_${plan.name}.plan.json`);
    let approved = false;
    if (o.approve) {
      const a = JSON.parse(fs.readFileSync(path.resolve(o.approve), 'utf8'));
      if (a.planHash !== planHash(a)) throw new PresenterError(`--approve ${o.approve}: the plan file was edited after it was made (hash mismatch)`);
      if (a.planHash !== plan.planHash) throw new PresenterError(`--approve ${o.approve}: it doesn't match this run (script, host, backends or consent changed); plan again and review`);
      approved = true;
    }
    fs.writeFileSync(planFile, JSON.stringify(plan, null, 1));
    fs.writeFileSync(path.join(out, 'PLAN.txt'), planText(plan));
    log(`plan: ${planFile}`);
    process.stderr.write(planText(plan).split('\n').slice(0, 10).map((l) => `  ${l}`).join('\n') + '\n');
    if (o.planOnly) { log('--plan-only: stopped after planning'); return 0; }
    if (plan.willSend.length && !approved) { log(`approval needed: this plan would send ${plan.willSend.join('; ')}. Review PLAN.txt, then re-run with --approve ${planFile}`); return 0; }
    const res = await renderPresenter(plan, { out, approved, offline: o.offline, log });
    for (const e of res.exports) {
      log(`${e.pass ? 'ok' : 'CHECK FAIL'} ${e.file}`);
      for (const c of e.checks) log(`  ${c.pass ? 'PASS' : 'FAIL'} ${c.id}: ${c.text}`);
    }
    log(`report ${res.reportFile}`);
    return res.exports.every((e) => e.pass) ? 0 : 1;
  } catch (e) {
    if (e instanceof PresenterError) { log(e.message); return 2; }
    if (e instanceof PendingAssetsError) { process.stdout.write(pendingMessage(e, { resumeCmd: 'the same command again (the saved assets are picked up)' })); return EXIT_PENDING; }
    throw e;
  }
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  presenterMain(process.argv.slice(2)).then((c) => process.exit(c), (e) => { console.error(`ai-video-editor: ${e.stack || e.message}`); process.exit(1); });
}
